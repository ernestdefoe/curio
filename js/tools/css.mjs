// Compiles less/pages.less into a module the lazy page chunks import, so
// Curio's page styles load with its pages instead of riding in forum.css.
import fs from 'node:fs';
import less from 'less';

const source = fs.readFileSync(new URL('../../less/pages.less', import.meta.url), 'utf8');
const { css } = await less.render(source, { compress: true });

// generated/ is not committed, so a fresh checkout makes it here.
fs.mkdirSync(new URL('../generated/', import.meta.url), { recursive: true });
fs.writeFileSync(
  new URL('../generated/pagesCss.js', import.meta.url),
  `// Generated by tools/css.mjs from less/pages.less. Do not edit.\nexport default ${JSON.stringify(css)};\n`
);
